#[test]
fn constructs_outside_the_value_model_are_errors() {
    for (text, why) in [
        ("1: x\n", "int key"),
        ("1.5: x\n", "float key"),
        ("true: x\n", "bool key"),
        ("~: x\n", "null key"),
        (": x\n", "empty key"),
        ("2026-01-02: x\n", "date key"),
        ("? [a]\n: x\n", "sequence key"),
        ("? {a: 1}\n: x\n", "mapping key"),
        ("a: !!binary aGk=\n", "binary"),
        ("a: !!set {x}\n", "set"),
        ("a: !!omap [{x: 1}]\n", "omap"),
        ("a: !foo x\n", "local tag"),
        ("a: !!str 12\n", "explicit str tag"),
        ("a: ! 12\n", "non-specific tag"),
        ("a: !!python/name:os.system x\n", "python tag"),
        ("<<: {b: 1}\n", "merge key"),
        ("a: {<<: {b: 1}}\n", "nested merge key"),
        ("a: <<\n", "merge value"),
        ("a: =\n", "value tag"),
        ("a: &x [1, *x]\n", "recursive alias"),
        ("a: *nope\n", "undefined alias"),
    ] {
        assert!(load(text).is_err(), "{why}: {text:?} should be an error");
    }
}

#[test]
fn invalid_yaml_is_an_error_with_a_position() {
    let e = load("title: Foo: bar\n").unwrap_err();
    assert_eq!(e.line, 1, "{e}");
    let e = load("a: 1\nb: [unclosed\n").unwrap_err();
    assert!(e.line >= 2, "{e}");
    let e = load("a: 1\n  b: 2\n").unwrap_err();
    assert!(!e.message.is_empty());
}

#[test]
fn error_positions_point_at_the_construct() {
    let e = load("a: x\nb:\n  1: y\n").unwrap_err();
    assert_eq!((e.line, e.column), (3, 3), "{e}");
    assert!(e.message.contains("int"), "{e}");
}

#[test]
fn alias_bombs_are_refused_not_expanded() {
    let mut text = String::from("a0: &a0 [x, x, x, x, x, x, x, x, x, x]\n");
    for n in 1..12 {
        let p = n - 1;
        text.push_str(&format!(
            "a{n}: &a{n} [*a{p}, *a{p}, *a{p}, *a{p}, *a{p}, *a{p}, *a{p}, *a{p}, *a{p}, *a{p}]\n"
        ));
    }
    assert!(load(&text).is_err());
}

#[test]
fn deep_nesting_is_an_error_not_a_crash() {
    let text = format!("a: {}{}\n", "[".repeat(5000), "]".repeat(5000));
    assert!(load(&text).is_err());
}
