//! The YAML reader against PyYAML 6.0.3 (`SafeLoader`, YAML 1.1).

use kluris_core::yaml::{Date, DateTime, Map, Value, load};
use num_bigint::BigInt;

type Expected = Option<Value>;

fn b(v: bool) -> Expected {
    Some(Value::Bool(v))
}

fn int(digits: &str) -> Expected {
    Some(Value::Int(digits.parse::<BigInt>().unwrap()))
}

fn flt(repr: &str) -> Expected {
    Some(Value::Float(repr.parse::<f64>().unwrap()))
}

fn s(text: &str) -> Expected {
    Some(Value::Str(text.to_string()))
}

fn null() -> Expected {
    Some(Value::Null)
}

fn date(y: u32, m: u32, d: u32) -> Expected {
    Some(Value::Date(Date::new(y, m, d).unwrap()))
}

#[allow(clippy::too_many_arguments)]
fn dt(y: u32, mo: u32, d: u32, h: u32, mi: u32, sec: u32, us: u32, off: Option<i32>) -> Expected {
    let date = Date::new(y, mo, d).unwrap();
    Some(Value::DateTime(
        DateTime::new(date, h, mi, sec, us, off).unwrap(),
    ))
}

fn err() -> Expected {
    None
}

