fn map(entries: Vec<(&str, Value)>) -> Value {
    Value::Map(
        entries
            .into_iter()
            .map(|(k, v)| (k.to_string(), v))
            .collect::<Map>(),
    )
}

fn str_(text: &str) -> Value {
    Value::Str(text.to_string())
}

fn i(n: i64) -> Value {
    Value::Int(BigInt::from(n))
}

#[test]
fn scalars_resolve_like_pyyaml() {
    let mut failures = Vec::new();
    for (case, expected) in scalars() {
        let got = load(&format!("v: {case}"));
        let ok = match (&got, &expected) {
            (Ok(Value::Map(m)), Some(want)) => m.len() == 1 && m.get("v") == Some(want),
            (Err(_), None) => true,
            _ => false,
        };
        if !ok {
            failures.push(format!(
                "  v: {case:?}\n    want {expected:?}\n    got  {got:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} scalars differ from PyYAML:\n{}",
        failures.len(),
        scalars().len(),
        failures.join("\n")
    );
}

#[test]
fn brief_examples_have_exact_types() {
    let v = |case: &str| load(&format!("v: {case}")).map(|doc| doc.as_map().unwrap()["v"].clone());
    assert_eq!(v("yes"), Ok(Value::Bool(true)));
    assert_eq!(v("0755"), Ok(i(493)));
    assert_eq!(v("1:30"), Ok(i(90)));
    assert_eq!(v("1_000"), Ok(i(1000)));
    assert_eq!(v("0o17"), Ok(str_("0o17")));
    assert_eq!(v("1e3"), Ok(str_("1e3")));
    assert_eq!(v("1.0e+3"), Ok(Value::Float(1000.0)));
    assert_eq!(
        v("2026-01-02"),
        Ok(Value::Date(Date::new(2026, 1, 2).unwrap()))
    );
    assert_eq!(v("2026-1-2"), Ok(str_("2026-1-2")));
    assert_eq!(v("2026-01-02 10:00"), Ok(str_("2026-01-02 10:00")));
    let utc = v("2026-01-02T10:00:00Z").unwrap();
    let Value::DateTime(t) = utc else {
        panic!("not a datetime: {utc:?}")
    };
    assert_eq!(t.date(), Date::new(2026, 1, 2).unwrap());
    assert_eq!(
        (t.hour(), t.minute(), t.second(), t.microsecond()),
        (10, 0, 0, 0)
    );
    assert_eq!(t.utc_offset(), Some(0));
    assert_eq!(v("~"), Ok(Value::Null));
    assert_eq!(v(""), Ok(Value::Null));
    assert_eq!(v("y"), Ok(str_("y")));
    assert_eq!(v("n"), Ok(str_("n")));
}

#[test]
fn big_ints_keep_every_digit() {
    let doc =
        load("big: 1000000000000000000000000000000\nneg: -0x_FFFF_FFFF_FFFF_FFFF_FFFF\n").unwrap();
    let m = doc.as_map().unwrap();
    let ten30 = BigInt::from(10u8).pow(30);
    assert_eq!(m["big"], Value::Int(ten30));
    assert_eq!(
        m["neg"],
        Value::Int(-"1208925819614629174706175".parse::<BigInt>().unwrap())
    );
}

#[test]
fn nan_and_infinities() {
    let doc = load("a: .nan\nb: .inf\nc: -.Inf\nd: -0.0\n").unwrap();
    let m = doc.as_map().unwrap();
    assert!(matches!(m["a"], Value::Float(f) if f.is_nan()));
    assert_eq!(m["b"], Value::Float(f64::INFINITY));
    assert_eq!(m["c"], Value::Float(f64::NEG_INFINITY));
    assert_eq!(m["d"], Value::Float(-0.0));
    assert_ne!(m["d"], Value::Float(0.0));
}

#[test]
fn nested_maps_keep_insertion_order() {
    let doc = load("zeta: 1\nalpha:\n  z: a\n  b: 2\n  m:\n    y: 1\n    a: 2\nmid: x\n").unwrap();
    let m = doc.as_map().unwrap();
    assert_eq!(m.keys().collect::<Vec<_>>(), ["zeta", "alpha", "mid"]);
    let inner = m["alpha"].as_map().unwrap();
    assert_eq!(inner.keys().collect::<Vec<_>>(), ["z", "b", "m"]);
    let deeper = inner["m"].as_map().unwrap();
    assert_eq!(deeper.keys().collect::<Vec<_>>(), ["y", "a"]);
}

#[test]
fn repeated_key_keeps_first_position_and_last_value() {
    let doc = load("a: 1\nb: 3\na: 2\n").unwrap();
    assert_eq!(doc, map(vec![("a", i(2)), ("b", i(3))]));
}

#[test]
fn block_and_flow_collections() {
    let doc = load(
        "tags: [on, off, 2026, kluris]\nflow: {b: 1, a: [x, 'y']}\nblock:\n- one\n-   - nested\n- k: v\nempty_list: []\nempty_map: {}\n",
    )
    .unwrap();
    let want = map(vec![
        (
            "tags",
            Value::Seq(vec![
                Value::Bool(true),
                Value::Bool(false),
                i(2026),
                str_("kluris"),
            ]),
        ),
        (
            "flow",
            map(vec![
                ("b", i(1)),
                ("a", Value::Seq(vec![str_("x"), str_("y")])),
            ]),
        ),
        (
            "block",
            Value::Seq(vec![
                str_("one"),
                Value::Seq(vec![str_("nested")]),
                map(vec![("k", str_("v"))]),
            ]),
        ),
        ("empty_list", Value::Seq(vec![])),
        ("empty_map", map(vec![])),
    ]);
    assert_eq!(doc, want);
}

#[test]
fn anchors_and_aliases_resolve_to_copies() {
    let doc = load("base: &b {x: 1, y: [a, b]}\ncopy: *b\nname: &n kluris\nagain: *n\n").unwrap();
    let m = doc.as_map().unwrap();
    assert_eq!(m["copy"], m["base"]);
    assert_eq!(m["again"], str_("kluris"));
    let doc = load("&k key: *k\n").unwrap();
    assert_eq!(doc, map(vec![("key", str_("key"))]));
}

#[test]
fn block_scalars_and_quoted_scalars_are_strings() {
    let doc = load(
        "lit: |\n  yes\n  0755\nfold: >\n  a\n  b\nsq: 'on'\ndq: \"1:30\"\nml: line1\n  line2\n",
    )
    .unwrap();
    let want = map(vec![
        ("lit", str_("yes\n0755\n")),
        ("fold", str_("a b\n")),
        ("sq", str_("on")),
        ("dq", str_("1:30")),
        ("ml", str_("line1 line2")),
    ]);
    assert_eq!(doc, want);
}

#[test]
fn documents_like_safe_load() {
    assert_eq!(load(""), Ok(Value::Null));
    assert_eq!(load("# only a comment\n"), Ok(Value::Null));
    assert_eq!(load("---\n"), Ok(Value::Null));
    assert_eq!(load("--- 5\n"), Ok(i(5)));
    assert_eq!(load("- a\n- 1\n"), Ok(Value::Seq(vec![str_("a"), i(1)])));
    assert_eq!(
        load("%YAML 1.1\n---\na: yes\n"),
        Ok(map(vec![("a", Value::Bool(true))]))
    );
    assert!(load("--- 1\n--- 2\n").is_err(), "two documents");
}

#[test]
fn crlf_text_reads_like_lf() {
    let doc = load("a: yes\r\nb:\r\n- x\r\nc: |\r\n  l1\r\n  l2\r\n").unwrap();
    let want = map(vec![
        ("a", Value::Bool(true)),
        ("b", Value::Seq(vec![str_("x")])),
        ("c", str_("l1\nl2\n")),
    ]);
    assert_eq!(doc, want);
}

