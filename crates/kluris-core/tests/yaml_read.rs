#[test]
fn brief_examples_have_exact_types() {
    let v = |case: &str| load(&format!("v: {case}")).map(|doc| doc.as_map().unwrap()["v"].clone());
    assert_eq!(v("yes"), Ok(Value::Bool(true)));
    assert_eq!(v("0755"), Ok(i(493)));
    assert_eq!(v("1:30"), Ok(i(90)));
    assert_eq!(v("1_000"), Ok(i(1000)));
    assert_eq!(v("0o17"), Ok(str_("0o17")));
    assert_eq!(v("1e3"), Ok(str_("1e3")));
    assert_eq!(v("1.0e+3"), Ok(Value::Float(1000.0)));
    assert_eq!(
        v("2026-01-02"),
        Ok(Value::Date(Date::new(2026, 1, 2).unwrap()))
    );
    assert_eq!(v("2026-1-2"), Ok(str_("2026-1-2")));
    assert_eq!(v("2026-01-02 10:00"), Ok(str_("2026-01-02 10:00")));
    let utc = v("2026-01-02T10:00:00Z").unwrap();
    let Value::DateTime(t) = utc else {
        panic!("not a datetime: {utc:?}")
    };
    assert_eq!(t.date(), Date::new(2026, 1, 2).unwrap());
    assert_eq!(
        (t.hour(), t.minute(), t.second(), t.microsecond()),
        (10, 0, 0, 0)
    );
    assert_eq!(t.utc_offset(), Some(0));
    assert_eq!(v("~"), Ok(Value::Null));
    assert_eq!(v(""), Ok(Value::Null));
    assert_eq!(v("y"), Ok(str_("y")));
    assert_eq!(v("n"), Ok(str_("n")));
}

