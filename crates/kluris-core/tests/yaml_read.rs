fn map(entries: Vec<(&str, Value)>) -> Value {
    Value::Map(
        entries
            .into_iter()
            .map(|(k, v)| (k.to_string(), v))
            .collect::<Map>(),
    )
}

fn str_(text: &str) -> Value {
    Value::Str(text.to_string())
}

fn i(n: i64) -> Value {
    Value::Int(BigInt::from(n))
}

fn check_rows(rows: Vec<(&'static str, Expected)>) {
    check(
        rows,
        |case| format!("v: {case}"),
        |doc| match doc.as_map() {
            Some(m) if m.len() == 1 => m.get("v").cloned(),
            _ => None,
        },
    );
}

fn check(
    rows: Vec<(&'static str, Expected)>,
    text: impl Fn(&str) -> String,
    pick: impl Fn(Value) -> Option<Value>,
) {
    let total = rows.len();
    let mut failures = Vec::new();
    for (case, expected) in rows {
        let got = load(&text(case));
        let ok = match (&got, &expected) {
            (Ok(doc), Some(want)) => pick(doc.clone()).as_ref() == Some(want),
            (Err(_), None) => true,
            _ => false,
        };
        if !ok {
            failures.push(format!(
                "  {case:?}\n    want {expected:?}\n    got  {got:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} rows differ from PyYAML:\n{}",
        failures.len(),
        total,
        failures.join("\n")
    );
}

