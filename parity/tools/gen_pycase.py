"""Python 3.11's case data, from the oracle, for ``kluris_core::pycase``.

Run in the oracle venv (Python 3.11, Unicode 14.0.0)::

    parity/.oracle/venv/bin/python -I parity/tools/gen_pycase.py [--check]

It writes two files (``--check`` writes nothing and exits 1 when either is
stale):

- ``crates/kluris-core/src/pycase_tables.rs``: what CPython's ``do_title`` and
  ``lower_ucs4`` (Objects/unicodeobject.c) read from its Unicode database:
  each code point's full titlecase and lowercase mapping where it is not the
  code point itself, and the ``Cased`` and ``Case_Ignorable`` ranges.
  ``Cased`` is ``Lowercase`` ∪ ``Uppercase`` ∪ ``Lt`` (``str.islower``,
  ``str.isupper`` and the category of one character). ``Case_Ignorable`` is
  read off ``str.lower``'s final-sigma rule: for a character ``x`` that is
  not cased, ``("A" + x + "Σ").lower()`` ends in ``ς`` exactly when ``x`` is
  case-ignorable; for a cased ``x``, ``("1" + x + "Σ").lower()`` ends in
  ``σ`` exactly when it is.
- ``crates/kluris-core/tests/fixtures/py_title.tsv``: ``str.title()`` of every
  code point it changes, then of strings that exercise the context (word
  starts, final sigma, case-ignorable runs), as hex code points.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / "crates" / "kluris-core" / "src" / "pycase_tables.rs"
EXPECT = ROOT / "crates" / "kluris-core" / "tests" / "fixtures" / "py_title.tsv"

CONTEXT = [
    "ΟΣ", "ΣΑΣ ΣΑΣ", "ΑΣ.Β", "ΑΣ'Β", "Α'Σ", "αΣ", "Σ", "ΣΣ", "ΑΣ́", "ΑΣ́Β", "ᾼΣ",
    "1Σ", "ΑΣ1", "ΑΣ­Β", "ΑΣ:", "ΑΣ’", "თბილისი", "ᾈ", "ᾈᾈ", "ǆemal ǅ ǆ", "ŉ ŉa",
    "ß straße", "ﬁle ﬂ", "o'neil o’neil", "2nd 3rd", "don't", "ALL CAPS", "mixed-Case_word",
    "ǰ", "ΐ", "ʼn", "İstanbul", "ǈ ǋ ǲ", "ⓐⓑ", "ꭰꭱ", "𐐨𐐩", "Ꮳ", "ꞵ", "ʰa", "aʰb",
]


def cased(c: str) -> bool:
    return c.islower() or c.isupper() or unicodedata.category(c) == "Lt"


def case_ignorable(c: str) -> bool:
    if cased(c):
        return ("1" + c + "Σ").lower().endswith("σ")
    return ("A" + c + "Σ").lower().endswith("ς")


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield chr(cp)


def ranges(flags: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in flags:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def tables() -> str:
    title, lower, cased_cps, ignorable_cps = [], [], [], []
    for c in chars():
        cp = ord(c)
        if c.title() != c:
            title.append((cp, c.title()))
        if c.lower() != c:
            lower.append((cp, c.lower()))
        if cased(c):
            cased_cps.append(cp)
        if case_ignorable(c):
            ignorable_cps.append(cp)
    lines = [
        "// @generated by parity/tools/gen_pycase.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit; rerun the generator.",
        "",
        "/// Full titlecase mappings that are not the character itself.",
        "pub(crate) static TITLE: &[(u32, &str)] = &[",
        *(f"    (0x{cp:x}, {rust_str(m)})," for cp, m in title),
        "];",
        "",
        "/// Full lowercase mappings that are not the character itself.",
        "pub(crate) static LOWER: &[(u32, &str)] = &[",
        *(f"    (0x{cp:x}, {rust_str(m)})," for cp, m in lower),
        "];",
        "",
        "/// `Cased` code point ranges, inclusive.",
        "pub(crate) static CASED: &[(u32, u32)] = &[",
        *(f"    (0x{a:x}, 0x{b:x})," for a, b in ranges(cased_cps)),
        "];",
        "",
        "/// `Case_Ignorable` code point ranges, inclusive.",
        "pub(crate) static CASE_IGNORABLE: &[(u32, u32)] = &[",
        *(f"    (0x{a:x}, 0x{b:x})," for a, b in ranges(ignorable_cps)),
        "];",
        "",
    ]
    return "\n".join(lines)


def hexes(s: str) -> str:
    return " ".join(f"{ord(c):x}" for c in s)


def expectations() -> str:
    lines = [
        "# str.title() in Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}), "
        "from parity/tools/gen_pycase.py: <input code points>\\t<output code points>, hex",
    ]
    for c in chars():
        if c.title() != c:
            lines.append(f"{hexes(c)}\t{hexes(c.title())}")
    for s in CONTEXT:
        lines.append(f"{hexes(s)}\t{hexes(s.title())}")
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in ((TABLES, tables()), (EXPECT, expectations())):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
