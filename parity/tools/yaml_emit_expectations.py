# --- Rust output -----------------------------------------------------------


def rust_str(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ch.isprintable():
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):x}}}")
    return '"' + "".join(out) + '"'


def rust_value(value: object) -> str:
    if value is None:
        return "n()"
    if isinstance(value, bool):
        return f"b({str(value).lower()})"
    if isinstance(value, int):
        return f'i("{value}")'
    if isinstance(value, float):
        return f'f("{value!r}")'
    if isinstance(value, str):
        return f"s({rust_str(value)})"
    if isinstance(value, datetime.datetime):
        offset = value.utcoffset()
        off = "None" if offset is None else f"Some({int(offset.total_seconds())})"
        return (
            f"dt({value.year}, {value.month}, {value.day}, {value.hour}, "
            f"{value.minute}, {value.second}, {value.microsecond}, {off})"
        )
    if isinstance(value, datetime.date):
        return f"d({value.year}, {value.month}, {value.day})"
    if isinstance(value, list):
        return "sq(vec![" + ", ".join(rust_value(v) for v in value) + "])"
    if isinstance(value, dict):
        return "mp(" + rust_map(value) + ")"
    raise TypeError(repr(value))


def rust_map(value: dict) -> str:
    rows = ", ".join(f"({rust_str(k)}, {rust_value(v)})" for k, v in value.items())
    return f"vec![{rows}]"


def label(value: object) -> str:
    text = repr(value)
    return text if len(text) <= 60 else text[:57] + "..."


def emit_row(name: str, meta: dict) -> str:
    return (
        f"        row({rust_str(name)}, {rust_map(meta)},\n"
        f"            {rust_str(md(meta))},\n"
        f"            {rust_str(yml(meta))},\n"
        f"            {rust_str(config(meta))}),"
    )


def universal_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def v3_body(body: str) -> str:
    """The Kluris 3 body rule: leading whitespace-only lines go, the first text
    line keeps its indentation (python-frontmatter strips both)."""
    lines = universal_newlines(body).split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join(lines)


def markdown_expected(meta: dict, body: str, ending: str) -> str:
    out = frontmatter.dumps(frontmatter.Post(v3_body(body), **meta)) + "\n"
    stripped = universal_newlines(body).strip()
    if v3_body(body).strip() == stripped and v3_body(body).lstrip() == v3_body(body):
        # Same body as v2 reads it: v2's own writer must agree.
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "n.md"
            write_frontmatter(path, dict(meta), stripped)
            v2 = path.read_bytes().decode("utf-8")
        assert v2 == out, (meta, body, v2, out)
    return out.replace("\n", "\r\n") if ending == "crlf" else out


def neuron_expected(meta: dict, body: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "n.yml"
        _write_yaml_neuron(path, dict(meta), body)
        return path.read_bytes().decode("utf-8")


def generate() -> str:
    out = [BEGIN, "", "#[rustfmt::skip]", "fn scalar_rows() -> Vec<Row> {", "    vec!["]
    for value in SCALARS:
        out.append(emit_row(label(value), {"v": value}))
    out += ["    ]", "}", "", "#[rustfmt::skip]", "fn document_rows() -> Vec<Row> {", "    vec!["]
    for name, meta in DOCUMENTS:
        out.append(emit_row(name, meta))
    out += ["    ]", "}", "", "#[rustfmt::skip]", "fn markdown_rows() -> Vec<MarkdownRow> {", "    vec!["]
    for name, meta, body, ending in MARKDOWN:
        le = "LineEnding::Crlf" if ending == "crlf" else "LineEnding::Lf"
        out.append(
            f"        md_row({rust_str(name)}, {rust_map(meta)}, {rust_str(body)}, {le},\n"
            f"            {rust_str(markdown_expected(meta, body, ending))}),"
        )
    out += ["    ]", "}", "", "#[rustfmt::skip]", "fn yaml_neuron_rows() -> Vec<NeuronRow> {", "    vec!["]
    for name, meta, body in NEURONS:
        out.append(
            f"        neuron_row({rust_str(name)}, {rust_map(meta)}, {rust_str(body)},\n"
            f"            {rust_str(neuron_expected(meta, body))}),"
        )
    out += ["    ]", "}", "", END]
    return "\n".join(out)


def main() -> int:
    block = generate()
    if "--write" not in sys.argv[1:]:
        print(block)
        return 0
    text = TEST_FILE.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"no generated block in {TEST_FILE}")
    TEST_FILE.write_text(pattern.sub(lambda _: block, text, count=1), encoding="utf-8")
    print(f"wrote {TEST_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
