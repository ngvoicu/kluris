"""Generate the expected output of the Kluris 3 YAML writer from PyYAML 6.0.3.

Every row is computed by the code v2 runs, in the oracle venv:

- ``md``: ``yaml.dump(meta, Dumper=CSafeDumper, default_flow_style=False,
  allow_unicode=True)``, python-frontmatter's export (libyaml emitter);
- ``yml``: ``yaml.safe_dump(meta, sort_keys=True, default_flow_style=False)``,
  the YAML-neuron block before its ``# `` prefixes (pure-Python emitter);
- ``config``: ``yaml.dump(data, default_flow_style=False, sort_keys=False)``,
  ``~/.kluris/config.yml`` and ``kluris.yml`` (pure-Python emitter);
- markdown framing: ``frontmatter.dumps(Post(body, **meta)) + "\\n"``, checked
  against v2's own ``write_frontmatter`` wherever the v3 body rule agrees;
- YAML neurons: v2's ``_write_yaml_neuron``.

It prints the generated block of ``crates/kluris-core/tests/yaml_emit.rs``;
``--write`` replaces that block in place:

    parity/.oracle/venv/bin/python -I parity/tools/yaml_emit_expectations.py [--write]
"""

