"""Print the first code point (digit zero) of every run of Unicode decimal
digits Python's ``int()`` and ``float()`` accept, as the Rust table
``DIGIT_ZEROS`` in ``crates/kluris-core/src/yaml/resolve.rs``.

Python reads a character as a decimal digit when ``unicodedata.decimal`` has a
value for it (category Nd); every such character sits in a run of ten, zero to
nine. Run it with the oracle venv (Python 3.11, Unicode 14.0.0):

    parity/.oracle/venv/bin/python -I parity/tools/unicode_digits.py
"""

from __future__ import annotations

import sys
import unicodedata


def main() -> int:
    zeros = []
    for code in range(sys.maxunicode + 1):
        digit = unicodedata.decimal(chr(code), None)
        if digit is None:
            continue
        if code - digit not in zeros:
            zeros.append(code - digit)
    for zero in zeros:
        run = [unicodedata.decimal(chr(zero + d), None) for d in range(10)]
        assert run == list(range(10)), (hex(zero), run)
    assert int("".join(chr(z + 7) for z in zeros[:3])) == 777
    print(f"/// Unicode {unicodedata.unidata_version}: generated by `parity/tools/unicode_digits.py`.")
    print(f"/// Generated from the Unicode Character Database (Unicode {unicodedata.unidata_version}) via")
    print(f"/// Python {sys.version_info.major}.{sys.version_info.minor}; see LICENSE-Unicode.")
    print(f"const DIGIT_ZEROS: [u32; {len(zeros)}] = [")
    for i in range(0, len(zeros), 8):
        print("    " + " ".join(f"0x{z:05X}," for z in zeros[i : i + 8]))
    print("];")
    return 0


if __name__ == "__main__":
    sys.exit(main())
